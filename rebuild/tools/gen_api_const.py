#!/usr/bin/env python3
"""Generate api_const.inc from the Amiga NDK .i include files.

The rebuild source keeps the original instruction bytes in comments.  This
script adds symbolic names for the API constants that are already verified
by the call-site analysis (IDCMP/WFLG, IECODE, MODE/OFFSET, MEMF, ...).

Only a curated subset of symbols is emitted, so the include stays readable.
The values are parsed from the NDK; BITDEF macros are expanded as (1<<bit).
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

DEFAULT_NDK = Path(__file__).resolve().parent.parent / "ndk32" / "Include_I"

# (file relative to the NDK, symbol prefixes/names to keep)
SOURCES = [
    ("exec/memory.i", ("MEMF_",)),
    ("dos/dos.i", ("MODE_", "OFFSET_", "SHARED_LOCK", "EXCLUSIVE_LOCK",
                   "ACCESS_", "DOSTRUE", "DOSFALSE")),
    ("intuition/intuition.i", ("IDCMP_", "WFLG_")),
    ("intuition/screens.i", ("SCREENTYPE", "WBENCHSCREEN", "PUBLICSCREEN",
                             "CUSTOMSCREEN")),
    ("devices/inputevent.i", ("IECODE_", "IECLASS_", "IESUBCLASS_",
                              "IEQUALIFIER_")),
]

EQU_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s+EQU\s+([^;*]+)", re.I)
BITDEF_RE = re.compile(r"^\s*BITDEF\s+([A-Za-z_][A-Za-z0-9_]*)\s*,\s*"
                       r"([A-Za-z_][A-Za-z0-9_]*)\s*,\s*([0-9]+)", re.I)
HEX_RE = re.compile(r"\$([0-9A-Fa-f]+)")


class EvalError(Exception):
    pass


def evaluate(expr: str, known: dict[str, int]) -> int:
    expr = expr.strip()
    expr = HEX_RE.sub(lambda m: "0x" + m.group(1), expr)
    # Keep only safe characters for the evaluator.
    if re.search(r"[^0-9A-Fa-fxX()+\-<>&|~ ]", expr):
        raise EvalError(expr)
    names = set(re.findall(r"(?<![0-9A-Za-z_])[A-Za-z_][A-Za-z0-9_]*",
                           expr))
    for name in names:
        if name not in known:
            raise EvalError("unknown " + name)
    return int(eval(expr, {"__builtins__": {}}, dict(known)))


def parse_file(path: Path, prefixes: tuple[str, ...],
               known: dict[str, int]) -> list[tuple[str, int, str]]:
    found: list[tuple[str, int, str]] = []
    if not path.exists():
        return found
    for raw in path.read_text(errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("*") or line.startswith(";"):
            continue
        m = BITDEF_RE.match(line)
        if m:
            prefix, name, bit = m.groups()
            bit_value = int(bit)
            bit_symbol = (prefix + "B_" + name).upper()
            mask_symbol = (prefix + "F_" + name).upper()
            known[bit_symbol] = bit_value
            known[mask_symbol] = 1 << bit_value
            if any(mask_symbol == p or mask_symbol.startswith(p)
                   for p in prefixes):
                found.append((mask_symbol, 1 << bit_value, raw.strip()))
            continue
        m = EQU_RE.match(line)
        if not m:
            continue
        symbol, expr = m.groups()
        try:
            value = evaluate(expr, known)
        except EvalError:
            continue
        known[symbol] = value
        if any(symbol == p or symbol.startswith(p) for p in prefixes):
            found.append((symbol, value, raw.strip()))
    return found


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ndk", type=Path, default=DEFAULT_NDK)
    parser.add_argument("--out", type=Path,
                        default=Path(__file__).resolve().parent.parent /
                        "api_const.inc")
    args = parser.parse_args()

    known: dict[str, int] = {}
    by_source: list[tuple[str, list[tuple[str, int]]]] = []
    for rel, prefixes in SOURCES:
        found = parse_file(args.ndk / rel, prefixes, known)
        by_source.append((rel, [(s, v) for s, v, _ in found]))

    lines = [
        "; Amiga API constants for the verified rebuild.",
        "; Generated by tools/gen_api_const.py from the NDK .i files.",
        "; Values are the NDK EQUs; BITDEF macros are expanded as (1<<bit).",
        "",
    ]
    for rel, symbols in by_source:
        if not symbols:
            continue
        lines.append("; --- " + rel + " ---")
        for symbol, value in sorted(symbols):
            if value < 0:
                text = str(value)
            elif value <= 0xFFFF:
                text = "$%04X" % value
            else:
                text = "$%08X" % value
            lines.append("%-28s equ %s" % (symbol, text))
        lines.append("")

    args.out.write_text("\n".join(lines))
    total = sum(len(s) for _, s in by_source)
    print("written %s (%d symbols)" % (args.out, total))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
